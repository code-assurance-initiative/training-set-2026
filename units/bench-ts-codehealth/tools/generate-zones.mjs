// Regenerates src/infrastructure/zones/country-zones.generated.ts from data/country-zones.csv.
// Usage: node tools/generate-zones.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

const source = new URL('../data/country-zones.csv', import.meta.url);
const target = new URL('../src/infrastructure/zones/country-zones.generated.ts', import.meta.url);

const rows = (await readFile(source, 'utf8'))
  .split('\n')
  .slice(1)
  .filter((line) => line.trim().length > 0)
  .map((line) => {
    const match = /^([A-Z]{2}),"([^"]*)",(Z\d),(yes|no)$/.exec(line.trim());
    if (!match) throw new Error(`Bad row: ${line}`);
    return { code: match[1], name: match[2], zone: match[3], customs: match[4] === 'yes' };
  });

const lines = [
  '// @generated by tools/generate-zones.mjs from data/country-zones.csv. Do not edit by hand:',
  '// change the CSV and run `node tools/generate-zones.mjs`.',
  '',
  '/** The tariff zone for an ISO 3166-1 alpha-2 country code. */',
  'export function zoneFor(country: string): string {',
  '  switch (country) {',
];
for (const row of rows) {
  lines.push(`    case '${row.code}': // ${row.name}`, `      return '${row.zone}';`);
}
lines.push('    default:', "      return 'Z5';", '  }', '}', '');
lines.push('/** Whether a parcel to the country needs a customs declaration. */');
lines.push('export function requiresCustomsDeclaration(country: string): boolean {');
lines.push('  switch (country) {');
for (const row of rows) {
  lines.push(`    case '${row.code}':`, `      return ${String(row.customs)};`);
}
lines.push('    default:', '      return true;', '  }', '}', '');
await writeFile(target, lines.join('\n'));
